def txt(c):
    return "" if c is None or c.value is None else str(c.value).strip()


def add(ws, rows):
    keys = {txt(r[0]) for r in ws.iter_rows(min_col=1, max_col=1)}
    n = 0
    for r in rows:
        if r[0] in keys:
            continue
        ws.append(list(r))
        keys.add(r[0])
        n += 1
    return n


