def cell_text(c):
    return "" if c is None or c.value is None else str(c.value).strip()


def first_col_keys(ws):
    keys = set()
    for row in ws.iter_rows(min_row=1, max_col=1):
        t = cell_text(row[0])
        if t:
            keys.add(t)
    return keys


def append_rows(ws, rows, key_index=0):
    keys = first_col_keys(ws) if key_index == 0 else set()
    added = 0
    for r in rows:
        k = str(r[key_index]).strip()
        if key_index == 0 and k in keys:
            continue
        ws.append(list(r))
        keys.add(k)
        added += 1
    return added


def changelog_keys(ws):
    keys = set()
    for row in ws.iter_rows(min_row=1, max_col=3):
        t = cell_text(row[2]) if len(row) > 2 else ""
