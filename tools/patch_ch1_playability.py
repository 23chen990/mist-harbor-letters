def headers(ws) -> dict[str, int]:
    return {cell.value: i for i, cell in enumerate(ws[1]) if cell.value}


def setc(ws, row: int, col: dict[str, int], field: str, value) -> None:
    ws.cell(row, col[field] + 1, value)


def find(ws, col: dict[str, int], row_id: str) -> int:
    for row in range(2, ws.max_row + 1):
        if ws.cell(row, col["自动ID"] + 1).value == row_id:
            return row
    raise KeyError(row_id)


def get(ws, row: int, col: dict[str, int], field: str):
    return ws.cell(row, col[field] + 1).value


def insert_after(ws, after_row: int) -> int:
    ws.insert_rows(after_row + 1)
    for col_idx in range(1, ws.max_column + 1):
        target = ws.cell(after_row + 1, col_idx)
        target._style = copy(ws.cell(after_row, col_idx)._style)
    return after_row + 1


def fill_row(ws, row: int, col: dict[str, int], data: dict) -> None:
    for field, value in data.items():
        setc(ws, row, col, field, value)


