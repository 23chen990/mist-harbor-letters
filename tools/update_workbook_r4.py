def txt(c):
    return "" if c is None or c.value is None else str(c.value).strip()


for path in PATHS:
    wb = openpyxl.load_workbook(path)
    rep = []

    ws = wb["作者锁定因果"]
    rewritten = 0
    for row in ws.iter_rows(min_col=1, max_col=4):
        key = txt(row[0])
        if key in REWRITE:
            for i, v in enumerate(REWRITE[key]):
                if i < len(row):
                    row[i].value = v
            rewritten += 1
    keys = {txt(r[0]) for r in ws.iter_rows(min_col=1, max_col=1)}
    added = 0
    for r in LOCKS:
        if r[0] in keys:
            continue
        ws.append(list(r))
        keys.add(r[0])
        added += 1
    rep.append(("作者锁定因果", f"改写 {rewritten} / 追加 {added}"))

    ws = wb["CHANGELOG_v4"]
    seen = {txt(r[2]) for r in ws.iter_rows(min_col=1, max_col=3) if len(r) > 2}
    n = 0
    for r in CHANGELOG:
        if r[2].strip() in seen:
            continue
        ws.append(list(r))
        seen.add(r[2].strip())
        n += 1
    rep.append(("CHANGELOG_v4", f"追加 {n}"))

    ws = wb["写作说明"]
    keys = {txt(r[0]) for r in ws.iter_rows(min_col=1, max_col=1)}
    n = 0
    for r in WRITING:
        if r[0] in keys:
            continue
        ws.append(list(r))
        keys.add(r[0])
        n += 1
    rep.append(("写作说明", f"追加 {n}"))

    ws = wb["最新世界真相"]
    keys = {txt(r[0]) for r in ws.iter_rows(min_col=1, max_col=1)}
    n = 0
    for r in WORLD:
        if r[0] in keys:
            continue
        ws.append(list(r))
        keys.add(r[0])
        n += 1
    rep.append(("最新世界真相", f"追加 {n}"))

    wb.save(path)
    print(path)
    for name, s in rep:
        print(f"  {name}: {s}")
