def cell_text(c):
    return "" if c is None or c.value is None else str(c.value)


for path in PATHS:
    wb = openpyxl.load_workbook(path)
    ws = wb["最新世界真相"]

    patched, appended = [], 0
    names = set()

    for row in ws.iter_rows(min_col=1, max_col=6):
        name = cell_text(row[0]).strip()
        if name:
            names.add(name)
        if name in PATCH:
            for col, addition in PATCH[name].items():
                cell = row[col - 1]
                cur = cell_text(cell)
                if addition.lstrip("｜")[:24] in cur:
                    continue
                cell.value = (cur + addition) if cur else addition.lstrip("｜")
                patched.append(f"{name}[{col}]")

    for r in APPEND:
        if r[0] in names:
            continue
        ws.append(list(r))
        names.add(r[0])
        appended += 1

    wb.save(path)
    print(path)
    print(f"  更新人物行: {patched if patched else '无（已是最新）'}")
    print(f"  追加修补行: +{appended}")
